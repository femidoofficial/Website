function escapeHtml(value) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function inlineMarkdown(value) {
  let text = escapeHtml(value);
  text = text.replace(/\\([@.])/g, "$1");
  text = text.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
  return text;
}

function markdownToHtml(markdown) {
  // The source Markdown wraps some bold headings across multiple physical
  // lines (for example the main title). Join those lines before parsing.
  const rawLines = markdown.replace(/\r/g, "").split("\n");
  const lines = [];
  for (let i = 0; i < rawLines.length; i += 1) {
    const current = rawLines[i].trim();
    if (current.startsWith("**") && !current.endsWith("**")) {
      const parts = [current];
      while (i + 1 < rawLines.length) {
        i += 1;
        const next = rawLines[i].trim();
        if (next) parts.push(next);
        if (next.endsWith("**")) break;
      }
      lines.push(parts.join(" "));
    } else {
      lines.push(rawLines[i]);
    }
  }

  const html = [];
  let paragraph = [];
  let list = [];

  const flushParagraph = () => {
    if (paragraph.length) {
      const text = paragraph.join(" ").trim();
      if (text) html.push(`<p>${inlineMarkdown(text)}</p>`);
      paragraph = [];
    }
  };

  const flushList = () => {
    if (list.length) {
      html.push(`<ul>${list.map(item => `<li>${inlineMarkdown(item)}</li>`).join("")}</ul>`);
      list = [];
    }
  };

  for (const rawLine of lines) {
    const line = rawLine.trim();

    if (!line) {
      flushParagraph();
      flushList();
      continue;
    }

    if (line === "---") {
      flushParagraph();
      flushList();
      html.push("<hr />");
      continue;
    }

    // Main document title
    if (/^\*\*FemiDo Captain/i.test(line) && /\*\*$/.test(line)) {
      flushParagraph();
      flushList();
      html.push(`<h1>${inlineMarkdown(line.slice(2, -2))}</h1>`);
      continue;
    }

    // Section headings: **1. Introduction**
    const sectionMatch = line.match(/^\*\*(\d+)\.\s+(.+?)\*\*$/);
    if (sectionMatch) {
      flushParagraph();
      flushList();
      html.push(`<h2>${inlineMarkdown(sectionMatch[1] + ". " + sectionMatch[2])}</h2>`);
      continue;
    }

    // Subsection headings: **1.1 Purpose of the Terms**
    const subMatch = line.match(/^\*\*(\d+\.\d+)\s+(.+?)\*\*$/);
    if (subMatch) {
      flushParagraph();
      flushList();
      html.push(`<h3>${inlineMarkdown(subMatch[1] + " " + subMatch[2])}</h3>`);
      continue;
    }

    // Bullets from the source document
    if (/^[●•]\s*/.test(line)) {
      flushParagraph();
      list.push(line.replace(/^[●•]\s*/, "").trim());
      continue;
    }

    // Continuation of a bullet item in the source
    if (list.length && !/^\*\*/.test(line) && /^[A-Za-z(]/.test(line)) {
      // The source wraps bullet text over multiple lines.
      list[list.length - 1] += " " + line;
      continue;
    }

    flushList();
    paragraph.push(line);
  }

  flushParagraph();
  flushList();
  return html.join("\n");
}

